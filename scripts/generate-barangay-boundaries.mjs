#!/usr/bin/env node
// Regenerates src/data/barangayBoundaries.js from the official PSA/NAMRIA 2019
// barangay boundaries (PSGC-coded GeoJSON published by faeldon/philippines-json-maps).
//
//   node scripts/generate-barangay-boundaries.mjs
//
// Only barangays referenced by the coverage store are emitted, keyed as
// `Municipality::Barangay` using the store's spelling. Official boundaries are a
// tiling of each municipality, so no two entries overlap. Coordinates are rounded
// to 5 decimals (~1 m). MultiPolygon barangays (islands / split lots) are kept as
// MultiPolygon; consumers must handle both geometry types.

import fs from 'node:fs'
import path from 'node:path'

const SOURCE_BASE = 'https://raw.githubusercontent.com/faeldon/philippines-json-maps/master/2019/geojson/barangays/hires'
const OUT_FILE = path.resolve(process.cwd(), 'src/data/barangayBoundaries.js')

