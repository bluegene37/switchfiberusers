const round = n => Number(n.toFixed(5))
const roundRing = ring => ring.map(([x, y]) => [round(x), round(y)])
const roundGeometry = g => ({
  type: g.type,
  coordinates: g.type === 'Polygon'
    ? g.coordinates.map(roundRing)
    : g.coordinates.map(poly => poly.map(roundRing))
})

async function fetchMunicipality(code) {
  const url = `${SOURCE_BASE}/barangays-municity-ph${code}.0.1.json`
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${res.status} fetching ${url}`)
  return res.json()
}

const out = {}
const missing = []
for (const [municipality, code] of Object.entries(MUNICIPALITIES)) {
  const wanted = WANTED[municipality]
  if (!wanted) continue
  const fc = await fetchMunicipality(code)
  for (const [storeName, psaName] of Object.entries(wanted)) {
    const feature = fc.features.find(f => f.properties.ADM4_EN === psaName)
    if (!feature) {
      missing.push(`${municipality}::${storeName} (PSA "${psaName}")`)
      continue
    }
    out[`${municipality}::${storeName}`] = roundGeometry(feature.geometry)
  }
}

if (missing.length) {
  console.error('Missing PSA features:\n  ' + missing.join('\n  '))
  process.exit(1)
}

const lines = Object.entries(out).map(([k, g]) => `  ${JSON.stringify(k)}: ${JSON.stringify(g)}`)
const header = `// Official barangay administrative boundaries for Switch Fiber coverage areas.
// Source: Philippine Statistics Authority / NAMRIA 2019 barangay boundaries,
// PSGC-coded GeoJSON from https://github.com/faeldon/philippines-json-maps
// (2019/geojson/barangays/hires). Generated by scripts/generate-barangay-boundaries.mjs;
// do not edit by hand.
//
// Keys are \`Municipality::Barangay\` matching the coverage store entries. Official
// boundaries tile each municipality, so entries never overlap. "Darangan" is a
// sitio of official Barangay Kalawaan and is drawn with the Kalawaan boundary.
// Geometry is GeoJSON Polygon or MultiPolygon in [lng, lat] order.

export const barangayBoundaries = {
${lines.join(',\n')}
}
`
fs.writeFileSync(OUT_FILE, header)
console.log(`Wrote ${Object.keys(out).length} boundaries to ${path.relative(process.cwd(), OUT_FILE)}`)
